// Builds js/map-data.js: the world map as pre-projected SVG paths, so the page
// needs no map library at runtime. Run: cd tools && npm install && npm run build-map
import { readFileSync, writeFileSync } from "node:fs";
import { geoEqualEarth, geoPath, geoCentroid } from "d3-geo";
import { feature } from "topojson-client";

const W = 1000, H = 500;
const load = n => { const t = JSON.parse(readFileSync(new URL(`./node_modules/world-atlas/countries-${n}.json`, import.meta.url))); return feature(t, t.objects.countries).features.filter(f => f.properties.name !== "Antarctica"); };
// Outlines come from the light 110m file; countries too small for it (Malta, Singapore...) come from 50m as dots.
const all = load("110m");
const small = load("50m").filter(f => !all.some(a => a.properties.name === f.properties.name));
const projection = geoEqualEarth().fitExtent([[4, 4], [W - 4, H - 4]], { type: "FeatureCollection", features: all });
const path = geoPath(projection).digits(1);

// Hand-placed label points where the geometric centre falls badly (overseas territories).
const anchor = { "France": [2.3, 46.6], "United States of America": [-98, 39], "Norway": [9, 61], "United Kingdom": [-2, 53.5] };

const countries = all.map(f => {
  const name = f.properties.name;
  const [x, y] = projection(anchor[name] || geoCentroid(f));
  return { id: f.id || name, name, d: path(f), c: [Math.round(x * 10) / 10, Math.round(y * 10) / 10] };
}).filter(c => c.d);
for (const f of small) {
  const [x, y] = projection(geoCentroid(f));
  countries.push({ id: f.id || f.properties.name, name: f.properties.name, dot: true, c: [Math.round(x * 10) / 10, Math.round(y * 10) / 10] });
}
countries.sort((a, b) => a.name.localeCompare(b.name));

const out = `// Generated by tools/build-map.mjs from world-atlas (Natural Earth, public domain). Do not edit by hand.\nwindow.MAP = ${JSON.stringify({ w: W, h: H, countries })};\n`;
writeFileSync(new URL("../js/map-data.js", import.meta.url), out);
console.log(`${countries.length} countries, ${(out.length / 1024).toFixed(0)} KB`);
